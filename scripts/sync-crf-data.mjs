#!/usr/bin/env node
/**
 * scripts/crf-sweep-results.jsonl  ->  lib/seo/data/crf-sweep.json
 *
 * The jsonl is lab output: append-only, one line per encode, never edited.
 * The json is what the app imports. Keeping them as two files with an explicit
 * sync step is deliberate — the alternative was transcribing 18 rows by hand
 * into a TS module, which is exactly how a chart quietly stops matching the
 * measurement it claims to show.
 *
 *   node scripts/sync-crf-data.mjs           # regenerate
 *   node scripts/sync-crf-data.mjs --check   # fail if stale (CI / pre-commit)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'scripts/crf-sweep-results.jsonl');
const OUT = path.join(ROOT, 'lib/seo/data/crf-sweep.json');

const CHECK = process.argv.includes('--check');

if (!fs.existsSync(SRC)) {
  console.error(`  ✗ no measurements at ${path.relative(ROOT, SRC)}`);
  process.exit(1);
}

const rows = fs
  .readFileSync(SRC, 'utf8')
  .trim()
  .split('\n')
  .filter(Boolean)
  .map((l) => JSON.parse(l));

// Only the fields a chart is allowed to read. Dropping the rest keeps someone
// from plotting, say, encodeSec as if it said something about our service —
// it is this laptop's speed, not the production encoder's.
const KEEP = [
  'label',
  'source',
  'sourceHash',
  'width',
  'height',
  'fps',
  'durationSec',
  'sourceBytes',
  'codec',
  'preset',
  'crf',
  'videoBytes',
  'videoKbps',
  'vmafMean',
  'vmafMin',
  'ssim',
];

const clean = rows
  .map((r) => Object.fromEntries(KEEP.map((k) => [k, r[k]])))
  .sort((a, b) => a.label.localeCompare(b.label) || a.crf - b.crf);

const dates = rows.map((r) => r.ts).sort();

const payload = {
  $comment:
    'Generated by scripts/sync-crf-data.mjs from scripts/crf-sweep-results.jsonl. Do not edit by hand.',
  measuredAt: dates[dates.length - 1].slice(0, 10),
  encoder: 'local ffmpeg, libx264',
  note: 'Video only (-an). Audio is excluded so these bytes are pure video bitrate.',
  runs: clean,
};

const next = JSON.stringify(payload, null, 2) + '\n';
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

if (CHECK) {
  if (prev !== next) {
    console.error(
      `  ✗ ${path.relative(ROOT, OUT)} is stale — run: node scripts/sync-crf-data.mjs\n`
    );
    process.exit(1);
  }
  console.log(`  ✓ crf-sweep.json matches the jsonl (${clean.length} runs).\n`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, next);
console.log(
  `  ✓ ${clean.length} runs -> ${path.relative(ROOT, OUT)} (measured ${payload.measuredAt})\n`
);
